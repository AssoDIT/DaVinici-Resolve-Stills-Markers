def apply_naming_template(template, meta_block):
    """
    Resolve a naming template string using metadata tokens and return a
    sanitized filename stem (no extension, no path).

    Supported tokens (case-sensitive, % prefix):
      %Scene  %Shot  %Take  %Camera_#  %Clipname  %Timeline
      %Reel_Name  %Date  %FPS  %Resolution  %Source_TC
    """
    if not template:
        return ""

    full_meta  = meta_block.get("metadata", {}) or {}
    full_props = meta_block.get("clip_properties", {}) or {}

    def _m(*keys):
        for k in keys:
            v = full_meta.get(k) or full_props.get(k) or ""
            if v:
                return str(v).strip()
        return ""

    token_map = {
        "%Camera_#":    _m("Camera #", "Camera"),
        "%Reel_Name":   _m("Reel Name"),
        "%Source_TC":   meta_block.get("source_tc") or _m("Start TC") or "",
        "%Resolution":  _m("Resolution"),
        "%Timeline":    meta_block.get("timeline_name", ""),
        "%Clipname":    meta_block.get("clip_name", ""),
        "%Scene":       _m("Scene"),
        "%Shot":        _m("Shot"),
        "%Take":        _m("Take"),
        "%Date":        _m("Date Recorded", "Date"),
        "%FPS":         _m("FPS"),
        "%Frame":       str(meta_block.get("timeline_frame", "")),
        "%Clip_#":      _m("Clip #"),
    }

    result = template
    # Replace longest tokens first to avoid partial substitution
    for token in sorted(token_map, key=len, reverse=True):
        result = result.replace(token, token_map[token])

    # Sanitize: remove characters illegal in filenames
    illegal = r'\/:*?"<>|'
    for ch in illegal:
        result = result.replace(ch, "_")

    # Collapse multiple underscores, strip leading/trailing separators
    while "__" in result:
        result = result.replace("__", "_")
    result = result.strip("_- ")

    return result


def apply_vertical_9_16_crop(img_path, safety=100.0):
    """
    Rogne les côtés d'un still 16:9 pour ne garder que la zone 9:16 centrale.
    Aucun upscale — l'image de sortie a les dimensions du crop.
    """
    try:
        with Image.open(img_path) as img:
            W, H = img.size
            src = img.convert("RGB")

        # Zone 9:16 centrée
        crop_w = int(round(H * 9.0 / 16.0))
        crop_h = H

        safety_f = max(0.5, min(1.0, float(safety) / 100.0))
        if safety_f < 1.0:
            crop_w = int(round(crop_w * safety_f))
            crop_h = int(round(crop_h * safety_f))

        x = (W - crop_w) // 2
        y = (H - crop_h) // 2

        print(f"Vertical 9:16 crop: ({x},{y}) {crop_w}×{crop_h} safety={safety:.1f}%")

        cropped = src.crop((x, y, x + crop_w, y + crop_h))

        ext = os.path.splitext(img_path)[1].lower()
        if ext in (".jpg", ".jpeg"):
            cropped.save(img_path, quality=95)
        else:
            cropped.save(img_path)

        print(f"Vertical 9:16 crop applied: {os.path.basename(img_path)}")
    except Exception as e:
        print(f"Could not apply vertical 9:16 crop: {e}")

    return img_path


def apply_open_gate_crop(img_path, native_w, native_h, safety=100.0):
    """
    Extract the 16:9 delivery area from an open-gate still and upscale to 1920x1080.

    Two cases depending on the actual exported image ratio:
      - Image ~16:9 (timeline export): 3:2 content is pillarboxed (black left/right)
        → find the native content width (H * native_ratio), then crop the 16:9 centre
          of that content area (also removing top/bottom excess), upscale to 1920x1080.
      - Image ~native ratio (full sensor export): 16:9 is letterboxed inside
        → crop the 16:9 centre vertically, upscale to 1920x1080.
    """
    OUT_W, OUT_H = 1920, 1080

    try:
        delivery_ratio = 16.0 / 9.0
        native_ratio   = float(native_w) / float(native_h)

        with Image.open(img_path) as img:
            W, H = img.size
            src  = img.convert("RGB")

        actual_ratio = float(W) / float(H)
        print(f"Open gate crop: input {W}x{H} (ratio {actual_ratio:.3f}), "
              f"native {native_w}x{native_h} (ratio {native_ratio:.3f})")

        if actual_ratio >= (delivery_ratio - 0.05):
            # Timeline export (~16:9): content is pillarboxed
            # Step 1 – width of the native content inside the frame
            content_w = int(round(H * native_ratio))
            # Step 2 – 16:9 crop from within that content (crops top/bottom excess)
            crop_w = content_w
            crop_h = int(round(content_w / delivery_ratio))
            mode_log = "pillarbox + 16:9 crop"
        else:
            # Full sensor export (~native ratio): extract 16:9 centre vertically
            crop_w = W
            crop_h = int(round(W / delivery_ratio))
            mode_log = "16:9 centre crop"

        crop_w = min(crop_w, W)
        crop_h = min(crop_h, H)

        # Apply safety: <100% zooms in (tighter), >100% zooms out (wider)
        safety_f = max(0.5, float(safety) / 100.0)
        crop_w = min(int(round(crop_w * safety_f)), W)
        crop_h = min(int(round(crop_h * safety_f)), H)

        x = (W - crop_w) // 2
        y = (H - crop_h) // 2

        print(f"Open gate crop [{mode_log}]: box ({x},{y}) {crop_w}x{crop_h} safety={safety:.1f}% → upscale {OUT_W}x{OUT_H}")

        cropped = src.crop((x, y, x + crop_w, y + crop_h))
        resized = cropped.resize((OUT_W, OUT_H), Image.LANCZOS)

        ext = os.path.splitext(img_path)[1].lower()
        if ext in (".jpg", ".jpeg"):
            resized.save(img_path, quality=95)
        else:
            resized.save(img_path)

        print(f"Open gate crop applied: {os.path.basename(img_path)}")
    except Exception as e:
        print(f"Could not apply open gate crop: {e}")


def apply_native_ratio_crop(img_path, native_w, native_h, safety=100.0):
    """
    Crop the image to the native camera ratio and resize to native-ratio HD.
    Output: height=1080, width=round(1080 * native_ratio).
    E.g. Venice 1 6K 3:2 → 1620×1080.
    """
    OUT_H = 1080
    native_ratio = float(native_w) / float(native_h)
    OUT_W = round(OUT_H * native_ratio)
    try:
        with Image.open(img_path) as img:
            W, H = img.size
            src = img.convert("RGB")

        # Fit native-ratio rect centered on image (prefer full height)
        content_h = H
        content_w = int(round(H * native_ratio))
        if content_w > W:
            content_w = W
            content_h = int(round(W / native_ratio))

        safety_f = max(0.5, float(safety) / 100.0)
        crop_w = min(int(round(content_w * safety_f)), W)
        crop_h = min(int(round(content_h * safety_f)), H)

        x = (W - crop_w) // 2
        y = (H - crop_h) // 2

        print(f"Native ratio crop: {W}x{H} → crop ({x},{y}) {crop_w}x{crop_h} "
              f"safety={safety:.1f}% → {OUT_W}x{OUT_H}")

        cropped = src.crop((x, y, x + crop_w, y + crop_h))
        resized = cropped.resize((OUT_W, OUT_H), Image.LANCZOS)

        ext = os.path.splitext(img_path)[1].lower()
        if ext in (".jpg", ".jpeg"):
            resized.save(img_path, quality=95)
        else:
            resized.save(img_path)
    except Exception as e:
        print(f"Could not apply native ratio crop: {e}")

    return img_path


